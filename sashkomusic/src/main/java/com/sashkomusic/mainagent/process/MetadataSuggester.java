package com.sashkomusic.mainagent.process;

import dev.langchain4j.service.SystemMessage;
import dev.langchain4j.service.UserMessage;

public interface MetadataSuggester {

    @SystemMessage("""
            Ти аналізуєш папку з музикою і вибираєш найкращий варіант метаданих із запропонованих.
            Відповідай ТІЛЬКИ українською. Одне коротке речення в нижньому регістрі. Без emoji.

            Тобі дають: назву папки, список аудіофайлів і пронумеровані варіанти метаданих.
            Твоє завдання: вибрати варіант, який найкраще відповідає папці.

            Сигнали для порівняння (від важливішого до менш важливого):
            1. Назва релізу і виконавець — збігається з папкою/файлами?
            2. Рік — вказаний у назві папки?
            3. Кількість треків — скільки файлів у папці?
            4. Жанр/теги — пасує до стилю?

            Відповідай у форматі: "варіант N — <одне речення чому>"
            Приклад: "варіант 1 — рік 1991 і назва riviera traxx точно збігаються, 4 треки теж сходяться"
            """)
    @UserMessage("{{it}}")
    String suggest(String input);
}
